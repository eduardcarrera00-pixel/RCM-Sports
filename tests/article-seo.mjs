import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {Window} from 'happy-dom';
import seo from '../assets/cam-article-seo.js';
import {build,fetchArticles,previewHTML} from '../scripts/build-news-seo.mjs';

const id='00000000-0000-0000-0000-000000000001';
const article={id,is_public:true,title:'Final & "remontada" <img src=x onerror=alert(1)>',summary:'Un <b>gran</b> partido &amp; otra victoria.',image:'javascript:alert(1)',author:'CAM SPORTS',created_at:'2026-10-25T12:00:00Z'};
const index=await fs.readFile('index.html','utf8');
for (const tag of ['name="description"','rel="canonical"','property="og:title"','property="og:description"','property="og:image"','name="twitter:card"'])assert(index.includes(tag),tag+' must be present before JavaScript');
assert.match(index,/camArticleSeo\?\.setArticle\(article\)/);
assert.match(index,/camArticleSeo\?\.reset\(\)/);
const community=await fs.readFile('assets/community.js','utf8');
assert.match(community,/camArticleSeo\?\.shareURL/);
assert.match(community,/camArticleSeo\?\.unavailable/);
assert.equal(seo.imageURL('data:image/png;base64,x'),seo.defaults.image);
assert.equal(seo.imageURL('https://user:password@example.org/a.png'),seo.defaults.image);
assert.equal(seo.imageURL('assets/test.png'),'https://camsports.github.io/assets/test.png');
assert.equal(seo.describe({...article,summary:'',body:'<p>Texto del artículo.</p>'}).description,'Texto del artículo.');
assert.equal(seo.previewPath('../oops'),null);
assert.equal(seo.describe(article).published,'2026-10-25T12:00:00.000Z');

const w=new Window({url:'https://camsports.github.io/?article='+id});
w.fetch=async()=>new w.Response(JSON.stringify({version:1,ids:[id,'../bad']}),{status:200});
w.eval(await fs.readFile('assets/cam-article-seo.js','utf8'));
assert.equal(w.camArticleSeo.shareURL(id,'legacy'),'legacy','Do not share missing previews before the manifest loads');
await w.camArticleSeo.ready;
w.camArticleSeo.setArticle(article);
assert.equal(w.document.title,'Final & "remontada" | CAM SPORTS');
assert.equal(w.document.querySelector('meta[name="description"]').content,'Un gran partido & otra victoria.');
assert.equal(w.document.querySelector('link[rel="canonical"]').href,seo.articleURL(id));
assert.equal(w.document.querySelector('meta[property="og:image"]').content,seo.defaults.image);
assert.equal(w.document.querySelector('meta[property="article:published_time"]').content,'2026-10-25T12:00:00.000Z');
assert.equal(w.document.querySelectorAll('meta[property="og:title"]').length,1);
assert.equal(w.document.querySelector('img'),null,'Metadata must never interpret article HTML');
assert.equal(w.camArticleSeo.shareURL(id),'https://camsports.github.io/compartir/noticias/'+id+'/');
assert.equal(w.camArticleSeo.shareURL('not-generated','legacy'),'legacy');
w.camArticleSeo.unavailable();
assert.equal(w.document.querySelector('meta[name="robots"]').content,'noindex,follow');
w.camArticleSeo.reset();
assert.equal(w.document.title,seo.defaults.title);
assert.equal(w.document.querySelector('link[rel="canonical"]').href,seo.defaults.url);
assert.equal(w.document.querySelector('meta[property="article:published_time"]'),null);
assert.equal(w.document.querySelector('meta[name="robots"]'),null);
await w.happyDOM.close();

const html=previewHTML(article);
assert(!html.includes('onerror='));
assert(!html.includes('javascript:alert'));
assert.match(html,/property="og:title" content="Final &amp; &quot;remontada&quot; \| CAM SPORTS"/);
assert.match(html,/name="robots" content="noindex,follow"/);
assert(html.includes('location.replace('+JSON.stringify(seo.articleURL(id))+')'));
assert.throws(()=>previewHTML({...article,is_public:false}));
assert.throws(()=>previewHTML({...article,id:'../../x'}));
const root=await fs.mkdtemp(path.join(os.tmpdir(),'cam-seo-test-'));
try {
  let requested;
  const good=async url=>{requested=String(url);return {ok:true,json:async()=>[article]};};
  await build({root,fetcher:good});
  assert.match(requested,/is_public=eq.true/);
  assert.match(requested,/select=id%2Ctitle/);
  const file=path.join(root,'compartir/noticias',id,'index.html');
  assert.equal(await fs.readFile(file,'utf8'),html);
  const before=await fs.readFile(path.join(root,'assets/cam-article-previews.json'),'utf8');
  await assert.rejects(build({root,fetcher:async()=>({ok:false,status:503})}));
  await assert.rejects(build({root,fetcher:async()=>({ok:true,json:async()=>[{...article,is_public:false}]})}));
  assert.equal(await fs.readFile(file,'utf8'),html,'API failures must preserve existing previews');
  assert.equal(await fs.readFile(path.join(root,'assets/cam-article-previews.json'),'utf8'),before);
  await assert.rejects(fetchArticles(async()=>({ok:true,json:async()=>[article,article]})));
  await fs.mkdir(path.join(root,'compartir/noticias','manual'),{recursive:true});
  await fs.writeFile(path.join(root,'compartir/noticias','manual','index.html'),'preserve');
  await build({root,fetcher:async()=>({ok:true,json:async()=>[]})});
  await assert.rejects(fs.stat(file));
  assert.equal(await fs.readFile(path.join(root,'compartir/noticias','manual','index.html'),'utf8'),'preserve');
} finally {await fs.rm(root,{recursive:true,force:true});}
console.log('PASS: article metadata/reset, real share URLs, HTML escaping, public-only generation, safe API failures and stale preview cleanup.');
