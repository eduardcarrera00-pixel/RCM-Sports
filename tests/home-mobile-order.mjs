import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Window} from 'happy-dom';
const w=new Window({url:'https://camsports.github.io/'}),d=w.document;
d.body.innerHTML=fs.readFileSync('index.html','utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
let phone=true;const changes=[];
w.matchMedia=()=>({get matches(){return phone;},addEventListener:(event,fn)=>changes.push(fn)});
const featured=d.getElementById('picksFeatured'),hero=d.getElementById('heroSection');
const sidebar=d.getElementById('aeHomeSidebarFeatures'),originalSidebar=sidebar.parentElement;
const trending=d.getElementById('aeTrendingPortada'),community=d.querySelector('.editorial-community');
d.body.classList.add('ae-is-home');
w.eval(fs.readFileSync('assets/ae-home-weekly-layout.js','utf8'));
d.dispatchEvent(new w.Event('DOMContentLoaded'));
assert.equal(featured.nextElementSibling,hero,'Pick del editor directly precedes the latest news');
assert.equal(sidebar.parentElement,originalSidebar,'ranking previews no longer interrupt Pick → news');
const footer=d.getElementById('aeHomeTrendingMobileFooter');
assert.equal(footer.nextElementSibling,community,'Lo más leído directly precedes Opinadores distinguidos');
assert.equal(trending.parentElement,footer);
assert.equal(d.querySelectorAll('#picksFeatured,#aeTrendingPortada').length,2,'use live components without copies');
phone=false;changes.forEach(fn=>fn());
assert.equal(trending.parentElement,sidebar,'desktop retains its original sidebar');
assert.equal(featured.closest('#footballTakes')!==null,true,'desktop restores the actual Pick to Picks');
phone=true;changes.forEach(fn=>fn());
assert.equal(featured.nextElementSibling,hero);
assert.equal(footer.nextElementSibling,community);
console.log('PASS: mobile Home Pick → news, Lo más leído → Opinadores, live nodes and desktop restoration.');
w.happyDOM.abort();
