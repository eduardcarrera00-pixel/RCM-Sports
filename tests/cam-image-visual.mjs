import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Window} from 'happy-dom';

const editor=fs.readFileSync('assets/ae-site-images.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const migration=fs.readFileSync('supabase/migrations/20261022013000_site_image_visual_controls.sql','utf8');
assert.match(index,/cam-image-visual\.js/);
assert.ok(index.indexOf('cam-image-visual.js') < index.indexOf('ae-site-images.js'));
assert.match(editor,/ae_set_site_image_visual/);
assert.match(editor,/select\('key,url,focus_x,focus_y,alt,visual'\)/);
assert.match(editor,/camImageVisual\?\.preview/);
assert.match(migration,/rcm_is_editor\(\)/);
assert.match(migration,/revoke all on function public\.ae_set_site_image_visual/);

const w=new Window({url:'https://camsports.github.io/'});
w.innerWidth=1200;
w.document.body.innerHTML='<div id="focus"></div><div id="preview"></div>';
w.eval(fs.readFileSync('assets/cam-image-visual.js','utf8'));
assert.ok(w.camImageVisual);
const ui={focusBox:w.document.getElementById('focus'),preview:w.document.getElementById('preview')};
let changes=0;
w.camImageVisual.attach(ui,()=>changes++);
const target=w.document.createElement('img');
target.src='https://camsports.github.io/assets/cam-sports-logo.webp';
w.document.body.append(target);
w.camImageVisual.open('marca.logo','img',null,target,{x:40,y:55});
assert.equal(w.document.querySelector('[data-f="x"]').value,'40');
assert.equal(w.document.querySelector('[data-f="y"]').value,'55');
const zoom=w.document.querySelector('[data-f="zoom"]');
zoom.value='70';
zoom.dispatchEvent(new w.Event('input',{bubbles:true}));
assert.equal(w.camImageVisual.get().desktop.zoom,70);
assert.equal(w.camImageVisual.get().desktop.x,40);
assert.ok(changes>0);
const background=w.camImageVisual.bg({zoom:70,size:100,x:40,y:55,fit:'contain'});
assert.equal(background.size,'70% auto');
assert.equal(background.pos,'40% 55%');
w.document.querySelector('[data-device="mobile"]').click();
const mobileZoom=w.document.querySelector('[data-f="zoom"]');
mobileZoom.value='85';
mobileZoom.dispatchEvent(new w.Event('input',{bubbles:true}));
assert.equal(w.camImageVisual.get().mobile.zoom,85);
assert.equal(w.camImageVisual.get().desktop.zoom,70);
w.document.querySelector('[data-reset="zoom"]').click();
assert.equal(w.camImageVisual.get().mobile.zoom,100);
w.camImageVisual.img(target,{visual:{desktop:{size:60,zoom:70,x:35,y:45,fit:'contain',ratio:'1:1'}}});
assert.equal(target.style.getPropertyValue('object-fit'),'contain');
assert.equal(target.style.getPropertyValue('aspect-ratio'),'1 / 1');
assert.match(target.style.getPropertyValue('transform'),/0\.7/);
w.camImageVisual.img(target,null);
assert.equal(target.style.getPropertyValue('transform'),'');
console.log('PASS CAM SPORTS: zoom, position, mobile profile, legacy focus, preview and image reset');
await w.happyDOM.close();
