/* Photo editor regression: no republish, no changed news order or text. */
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
const index = fs.readFileSync('index.html','utf8');
const community = fs.readFileSync('assets/community.js','utf8');
const framing = fs.readFileSync('assets/ae-image-framing.js','utf8');
assert.match(index,/id="editArticlePhotoButton"[^>]*onclick="openArticlePhotoEditor\(\)"/);
assert.match(index,/id="aeArticlePhotoModal"/);
assert.match(index,/id="aePhotoImageFile"/);
assert.match(index,/id="aePhotoImageUrl"/);
assert.match(index,/id="aePhotoFocusX"/);
assert.match(index,/id="aePhotoZoomRange"/);
assert.match(index,/const changes = \{\s*image: safeImageURL\(url\),\s*image_focus_x: frame.x,\s*image_focus_y: frame.y,\s*image_zoom_pct: frame.zoom\s*\}/);
assert.match(index,/db\.from\('articles'\)\.update\(changes\)\s*\.eq\('id',articleId\)\.select\(\)\.single\(\)/);
assert.match(index,/articles = articles\.map\(a => String\(a.id\) === String\(articleId\)/);
assert.match(index,/articles = editingArticleId\s*\? articles\.map/);
assert.match(index,/let photoEditArticleId = null/);
assert.match(index,/window\.aeRefreshNewsArchive\?\.\(\)/);
assert.match(community,/\['editArticleButton','editArticlePhotoButton'\]/);
assert.match(framing,/photo:\{\s*file:'aePhotoImageFile'/);
const w = new Window({url:'https://camsports.github.io/'});
w.document.body.innerHTML = index.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
assert.ok(w.document.getElementById('aePhotoSaveButton'));
assert.ok(w.document.getElementById('aeArticlePhotoForm').querySelectorAll('input[type=file],input[type=url]').length===2);
assert.equal(w.document.getElementById('aeArticlePhotoModal').getAttribute('role'),'dialog');
assert.equal(w.document.getElementById('aePhotoImageFile').accept,'image/jpeg,image/png,image/webp');
console.log('PASS: photo-only editor targets existing article, updates only cover and framing, and preserves news order.');
await w.happyDOM.close();
