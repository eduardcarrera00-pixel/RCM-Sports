import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
const w = new Window({url:'https://example.test/'});
w.document.body.innerHTML = '<div id="publishModal"><form><label>Título</label><input id="title"><label>Contenido</label><textarea id="pubBody" required></textarea></form></div>';
const sanitized = [];
w.cleanBody = html => {sanitized.push(html); return html;};
w.eval(fs.readFileSync('assets/ae-news-editor.js', 'utf8'));
const editor = w.document.getElementById('aeNewsEditor');
const source = w.document.getElementById('pubBody');
assert.equal(source.hidden, true);
assert.equal(source.required, false);
assert.equal(w.document.querySelector('label').htmlFor, 'title');
const article = '<h2>Un título</h2><p>Texto <strong>importante</strong>.</p><ul><li>Primer punto</li></ul>';
w.aeNewsEditor.set(article);
assert.equal(w.aeNewsEditor.isDirty(), false);
assert.equal(w.aeNewsEditor.html(), article);
assert.equal(editor.querySelectorAll('strong,li,h2').length, 3);
editor.innerHTML = '<p>Contenido corregido</p>';
editor.dispatchEvent(new w.Event('input'));
assert.equal(source.value, 'Contenido corregido');
assert.equal(w.aeNewsEditor.isDirty(), true);
assert.match(w.document.getElementById('aeEditorCount').textContent, /2 palabras/);
editor.innerHTML = '<div>Primer párrafo</div><div>Segundo párrafo</div>';
editor.dispatchEvent(new w.Event('input'));
assert.equal(w.aeNewsEditor.html(), '<p>Primer párrafo</p><p>Segundo párrafo</p>');
editor.innerHTML = '<p><br></p>';
editor.dispatchEvent(new w.Event('input'));
assert.equal(w.aeNewsEditor.html(), '', 'An empty visual editor cannot publish blank HTML');
w.aeNewsEditor.set(article);
source.form.reset();
assert.equal(editor.innerHTML, '');
assert.equal(w.aeNewsEditor.isDirty(), false);
assert.ok(sanitized.includes(article));
for (const button of w.document.querySelectorAll('.ae-editor-toolbar button')) assert.equal(button.type, 'button');
const index = fs.readFileSync('index.html','utf8');
assert.match(index, /!window\.aeNewsEditor\?\.isDirty\(\)/, 'Formatting changes must not be overwritten by the original article');
assert.match(index, /body: window\.aeNewsEditor \? window\.aeNewsEditor\.html\(\)/);
console.log('PASS: editor preserves rich articles, tracks edits, synchronizes text, rejects empty content, resets, labels fields, and protects formatting-only changes.');
await w.happyDOM.close();
