create table if not exists public.nfl_ranking_history (
 id bigint generated by default as identity primary key,
 edition text not null,
 team_ids text[] not null,
 superseded_at timestamptz not null default now()
);
alter table public.nfl_ranking_history enable row level security;
revoke all on public.nfl_ranking_history from anon,authenticated,public;
grant select on public.nfl_ranking_history to anon,authenticated;
drop policy if exists ae_nfl_ranking_history_read on public.nfl_ranking_history;
create policy ae_nfl_ranking_history_read on public.nfl_ranking_history
for select to anon,authenticated using(true);

create or replace function public.ae_archive_nfl_ranking() returns trigger
language plpgsql security definer set search_path=public as $$
begin
 insert into public.nfl_ranking_history(edition,team_ids,superseded_at)
 values(old.edition,old.team_ids,now());
 return new;
end $$;
revoke all on function public.ae_archive_nfl_ranking() from public,anon,authenticated;
drop trigger if exists ae_nfl_ranking_archive on public.nfl_rankings;
create trigger ae_nfl_ranking_archive
after update on public.nfl_rankings
for each row when(old.team_ids is distinct from new.team_ids or old.edition is distinct from new.edition)
execute function public.ae_archive_nfl_ranking();

create table if not exists public.ae_article_views (
 article_id uuid primary key references public.articles(id) on delete cascade,
 views bigint not null default 0 check(views >= 0),
 updated_at timestamptz not null default now()
);
alter table public.ae_article_views enable row level security;
revoke all on public.ae_article_views from anon,authenticated,public;
grant select on public.ae_article_views to anon,authenticated;
drop policy if exists ae_article_views_read on public.ae_article_views;
create policy ae_article_views_read on public.ae_article_views
for select to anon,authenticated using(
 exists(select 1 from public.articles a where a.id=article_id and a.is_public)
);
create or replace function public.ae_record_article_view(p_article_id uuid)
returns bigint language plpgsql security definer set search_path=public as $$
declare result bigint;
begin
 if not exists(select 1 from public.articles where id=p_article_id and is_public=true) then return null; end if;
 insert into public.ae_article_views(article_id,views,updated_at)
 values(p_article_id,1,now())
 on conflict(article_id) do update set views=ae_article_views.views+1,updated_at=now()
 returning views into result;
 return result;
end $$;
revoke all on function public.ae_record_article_view(uuid) from public;
grant execute on function public.ae_record_article_view(uuid) to anon,authenticated;
notify pgrst,'reload schema';
